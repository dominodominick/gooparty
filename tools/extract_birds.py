#!/usr/bin/env python3
"""Make the birds over the island fly, using the game's own animation.

The birds (model m001_08 in the map) are 30 birds, each two flat wing cards, one bone per wing (wing_l_N / wing_r_N, the two
wings of a bird share their position). The converted map has them frozen where they are at frame 0. The game flies them
with the map animation  files/mr001/map/motion/m001_08.branm.lz  (CHR0, 6000 frames, looping): every wing has its own
keyed position and rotation (hermite curves, 400,000 keys in all).

This samples that animation every 2 frames (30 times a second), stores each bird's position (whole map units) and each
wing's rotation (quaternion, 1/32767 steps) as 16-bit deltas, gzips it, and writes js15/world/birdsData.js together with
the two wing cards (left, right) in their bones' own space. js15/world/birds.js plays it back.

Usage:  python3 tools/extract_birds.py path/to/m001_08.mdl0 path/to/m001_08.branm.lz
"""
import sys, os, json, base64, gzip, math
sys.path.insert(0, os.path.join(os.path.dirname(__file__), 'wii'))
import numpy as np
from lz import unlz
from brres import brres
from mdl0 import mdl0
from mesh import read_obj
from chr0 import chr0

STEP = 2
mdl, anm = sys.argv[1], sys.argv[2]
m = open(mdl, 'rb').read(); M = mdl0(m, 0)
d = open(anm, 'rb').read()
if d[:4] != b'bres': d = unlz(d)
A = chr0(d, brres(d)['AnmChr(NW4R)']['m001_08'])
FR = A['frames']

# ---- the two wing cards ----
by_mtx = {b['mtx']: i for i, b in enumerate(M['bones'])}
cards = {}
wing_side = {}
for o in M['objs']:
    bone = M['bones'][by_mtx.get(o['node'], o['node'])]
    arr = o['ids'][0]
    wing_side[bone['name']] = arr
    if arr in cards: continue
    verts, tris = read_obj(m, o)
    P = M['pos'][arr][1]; U = M['uv'][o['ids'][4]][1]
    pos = [P[v['pos']] for v in verts]; uv = [U[v['uv0']] for v in verts]
    cards[arr] = {'position': [round(float(x), 3) for p in pos for x in p], 'uv': [round(float(x), 5) for u in uv for x in u],
                  'index': [i for t in tris for i in (t[0], t[2], t[1])]}
assert sorted(cards) == [0, 1]
# check the rest pose: the bone's world matrix puts each card where the converted map has it (frame 0)
wings = [b['name'] for b in M['bones'] if b['name'] in wing_side]

def samp(tr, F):
    if isinstance(tr, float): return np.full(len(F), tr)
    k = np.array(tr); fr, v, t = k[:, 0], k[:, 1], k[:, 2]
    i = np.clip(np.searchsorted(fr, F, side='right') - 1, 0, len(fr) - 2)
    f0, f1 = fr[i], fr[i + 1]; span = np.maximum(f1 - f0, 1e-9); s = np.clip((F - f0) / span, 0, 1); s2 = s * s; s3 = s2 * s
    return v[i] * (2 * s3 - 3 * s2 + 1) + v[i + 1] * (-2 * s3 + 3 * s2) + (t[i] * (s3 - 2 * s2 + s) + t[i + 1] * (s3 - s2)) * span

def quat_zyx(rx, ry, rz):  # the Wii turns X, then Y, then Z:  R = Rz Ry Rx
    cx, sx = np.cos(rx / 2), np.sin(rx / 2); cy, sy = np.cos(ry / 2), np.sin(ry / 2); cz, sz = np.cos(rz / 2), np.sin(rz / 2)
    return np.stack([cz * cy * sx - sz * sy * cx, cz * sy * cx + sz * cy * sx, sz * cy * cx - cz * sy * sx, cz * cy * cx + sz * sy * sx], 1)

F = np.arange(0, FR, STEP, dtype=float)
T, Q, SCALE = {}, {}, {}
for n in wings:
    tr = A['bones'][n]['tracks']
    sc = [samp(c, F) for c in tr.get('S', [1.0, 1.0, 1.0])]  # each bird has its own size (0.6 to 1.2), the same all the way
    assert all(np.ptp(c) < 1e-6 for c in sc) and max(c[0] for c in sc) - min(c[0] for c in sc) < 1e-6, n
    SCALE[n] = round(float(sc[0][0]), 4)
    T[n] = np.stack([samp(c, F) for c in tr['T']], 1)
    q = quat_zyx(*[samp(c, F) * math.pi / 180 for c in tr['R']])
    for i in range(1, len(q)):
        if (q[i] * q[i - 1]).sum() < 0: q[i] = -q[i]
    Q[n] = q
# birds: wings that share a position
birds = []; bird_of = {}
for n in wings:
    for bi, b in enumerate(birds):
        if np.allclose(T[b[0]], T[n], atol=0.01): b.append(n); bird_of[n] = bi; break
    else: bird_of[n] = len(birds); birds.append([n])
pos = np.round(np.stack([T[b[0]] for b in birds], 1)).astype(np.int32)           # samples x birds x 3
quat = np.round(np.stack([Q[n] for n in wings], 1) * 32767).astype(np.int32)       # samples x wings x 4
chan = np.concatenate([pos.reshape(len(F), -1), quat.reshape(len(F), -1)], 1)     # samples x channels
delta = np.diff(chan, axis=0, prepend=np.zeros((1, chan.shape[1]), np.int32))
assert np.abs(delta[1:]).max() < 32767 and np.abs(chan[0]).max() < 32767
blob = gzip.compress(delta.T.astype('<i2').tobytes(), 9)                          # channel by channel
out = os.path.join(os.path.dirname(__file__), '..', 'js15', 'world', 'birdsData.js')
with open(out, 'w') as f:
    f.write('// Generated by tools/extract_birds.py from the game files m001_08.mdl0 and files/mr001/map/motion/m001_08.branm.lz. Do not edit.\n')
    f.write('export const BIRDS = ' + json.dumps({
        'frames': FR, 'step': STEP, 'samples': len(F), 'birds': len(birds),
        'wings': [{'bird': bird_of[n], 'side': wing_side[n], 'scale': SCALE[n], 'name': n} for n in wings],
        'cards': [cards[0], cards[1]],
        'motion': base64.b64encode(blob).decode(),
    }, separators=(',', ':')) + ';\n')
print(f'{len(birds)} birds, {len(wings)} wings, {len(F)} samples every {STEP} frames -> {os.path.normpath(out)} ({os.path.getsize(out)//1024} KB)')
