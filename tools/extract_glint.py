#!/usr/bin/env python3
"""The hit glint's pictures, from the board's effect textures (files/effect/e001_00.breft).

The board's effect e001_00_5, the one the game puts on the hit spots of the dragon wall and the summit gate, draws
mr001_e004 (a spiky burst: half of it, which the game mirrors), mr001_e009 (a soft glow) and the streak rings
mr001_e015 / mr001_e017. They are grey with alpha: the game tints them, here with the player's colour.

  python3 tools/extract_glint.py <e001_00.breft(.lz)>
writes js15/world/glintTex.js (PNG data URLs).
"""
import sys, os, re, struct, io, base64
sys.path.insert(0, os.path.join(os.path.dirname(__file__), 'wii'))
from lz import unlz
from tex0 import tex0
from PIL import Image, ImageOps

t = open(sys.argv[1], 'rb').read(); t = unlz(t) if t[:4] != b'REFT' else t
base = t.find(b'mr001_e000') - 2 - 4 - 4  # the texture table: u32 size, u16 count, then name / offset / size entries


def texture(name):
    m = re.search(name.encode() + rb'\x00', t)
    nl = struct.unpack('>H', t[m.start() - 2:m.start()])[0]; o = m.start() + nl
    off, _ = struct.unpack('>II', t[o:o + 8]); h = base + off
    w, hh, dsz, fmt = struct.unpack('>HHIB', t[h + 4:h + 13]) # header: 0x20 bytes, then the pixels
    fake = bytearray(0x40); fake[0:4] = b'TEX0'; fake[0x10:0x14] = struct.pack('>i', 0x40); fake[0x1C:0x24] = struct.pack('>HHI', w, hh, fmt)
    img, _ = tex0(bytes(fake) + t[h + 0x20:h + 0x20 + dsz], 0)
    return Image.fromarray(img, 'RGBA')


def url(im):
    b = io.BytesIO(); im.save(b, 'PNG', optimize=True); return 'data:image/png;base64,' + base64.b64encode(b.getvalue()).decode()


star = texture('mr001_e004').copy()     # 64 x 128: the right half of the burst, its middle on the right edge
px = star.load()
for y in range(star.height):            # (a sliver of a spike tip shows at the far left edge: not part of the burst)
    for x in range(4): px[x, y] = (255, 255, 255, 0)
full = Image.new('RGBA', (star.width * 2, star.height)); full.paste(star, (0, 0)); full.paste(ImageOps.mirror(star), (star.width, 0))
out = {'star': url(full), 'glow': url(texture('mr001_e009')), 'ring': url(texture('mr001_e015')), 'streak': url(texture('mr001_e017'))}
dst = os.path.join(os.path.dirname(__file__), '..', 'js15', 'world', 'glintTex.js')
with open(dst, 'w') as f:
    f.write('// Generated by tools/extract_glint.py from the board\'s effect textures (files/effect/e001_00.breft): the hit glint\n')
    f.write('// (effect e001_00_5): a spiky burst (mr001_e004, mirrored into a whole one), a soft glow (e009) and streak rings\n')
    f.write('// (e015, e017). Grey with alpha: tinted with the player\'s colour. Do not edit.\n')
    for k, v in out.items(): f.write(f'export const GLINT_{k.upper()} = {v!r};\n'.replace("'", '"'))
print('->', os.path.normpath(dst), os.path.getsize(dst) // 1024, 'KB')
