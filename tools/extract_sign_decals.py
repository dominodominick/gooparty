#!/usr/bin/env python3
"""The pictures on the wooden signs (an arrow at the start, a blue 4, a blue 3 at the volcano push).

In the game the sign material (mr001m023) has two layers: the wood (mr001_t023a, first UV set) and, over it, a picture
cut from one atlas (mr001_t023b: arrow / 4 / 3 / blank, top to bottom), placed by the sign's second UV set. The converted
map kept only the wood. This reads the second UV set of each sign (m001_00a1, m001_00c, m001_00e) from the game's
map.brres, in the order of the converted map's own vertices, and the atlas, and writes js15/world/signDecals.js.

Usage:  python3 tools/extract_sign_decals.py path/to/map.brres(.lz) path/to/island.glb
"""
import sys, os, json, struct, io, base64
sys.path.insert(0, os.path.join(os.path.dirname(__file__), 'wii'))
import numpy as np
from PIL import Image
from lz import unlz
from brres import brres
from mdl0 import mdl0
from mesh import read_obj
from tex0 import tex0

raw = open(sys.argv[1], 'rb').read(); d = raw if raw[:4] == b'bres' else unlz(raw)
R = brres(d); B = R['3DModels(NW4R)']
g = open(sys.argv[2], 'rb').read(); L = struct.unpack('<I', g[12:16])[0]; J = json.loads(g[20:20 + L]); bo = 20 + L + 8
def acc(i):
    a = J['accessors'][i]; bv = J['bufferViews'][a['bufferView']]; n = {'VEC3': 3, 'VEC2': 2}[a['type']]
    return np.frombuffer(g, '<f4', a['count'] * n, bo + bv.get('byteOffset', 0) + a.get('byteOffset', 0)).reshape(-1, n)
mi = [i for i, m in enumerate(J['materials']) if m['name'] == 'mr001m023'][0]
uv1 = {}
for me in J['meshes']:
    for p in me['primitives']:
        if p['material'] != mi: continue
        name = me['name']; GP = acc(p['attributes']['POSITION']); GU = acc(p['attributes']['TEXCOORD_0'])
        M = mdl0(d, B[name]); order = sorted(M['mats'], key=lambda n: M['mats'][n]); k = order.index('mr001m023')
        o = [M['objs'][x[2]] for x in M['defs']['DrawOpa'] + M['defs'].get('DrawXlu', []) if x[1] == k][0]
        vs, _ = read_obj(d, o); P = M['pos'][o['ids'][0]][1]; U0 = M['uv'][o['ids'][4]][1]; U1 = M['uv'][o['ids'][5]][1]
        mp = np.array([P[v['pos']] for v in vs]); m0 = np.array([U0[v['uv0']] for v in vs]); m1 = np.array([U1[v['uv1']] for v in vs])
        out = []
        for gi in range(len(GP)):
            err = np.abs(mp - GP[gi]).sum(1) + np.abs(m0 - GU[gi]).sum(1) * 100
            c = int(np.argmin(err)); assert err[c] < 0.01, (name, gi, err[c])
            out += [round(float(m1[c][0]), 4), round(float(m1[c][1]), 4)]
        uv1[name] = out
T = R['Textures(NW4R)']; a, _ = tex0(d, T['mr001_t023b'])
im = Image.fromarray(a, 'RGBA').resize((128, 256), Image.LANCZOS); buf = io.BytesIO(); im.save(buf, 'PNG', optimize=True)
url = 'data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode()
dst = os.path.join(os.path.dirname(__file__), '..', 'js15', 'world', 'signDecals.js')
with open(dst, 'w') as f:
    f.write('// Generated by tools/extract_sign_decals.py from the game\'s map.brres. Do not edit.\n')
    f.write('// The second layer of the sign material mr001m023: the picture atlas and each sign\'s second UV set, in the\n// order of the converted map\'s own vertices for that sign.\n')
    f.write('export const SIGN_DECALS = ' + json.dumps({'texture': url, 'uv1': uv1}, separators=(',', ':')) + ';\n')
print({k: len(v) // 2 for k, v in uv1.items()}, os.path.getsize(dst) // 1024, 'KB')
