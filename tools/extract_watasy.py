#!/usr/bin/env python3
"""Bring back the long-necked dinosaur that swims round the pool by the rope bridge ("watasy" in the game's files).

It is not in the converted map: it lives in the game's own NPC file  files/mr001/npc/mr001_03.brres.lz  on the disc.
This reads that file (LZ-compressed BRRES: one MDL0 model with a single bone, and its TEX0 textures) and writes
js15/world/watasyModel.js: the mesh (positions, normals, UVs, triangles) and its body texture as a PNG data URL.

How it moves is NOT taken from here: the game moves it with the map's own animation  files/mr001/map/motion/m001_09.branm
(CHR0, read by tools/wii/chr0.py), which turns out to be exact simple curves, written out in js15/world/watasy.js.
The model's own CHR0 (mr001_03_1) animates a neck skeleton this model does not have, so the game draws it rigid too.

Usage:  python3 tools/extract_watasy.py path/to/mr001_03.brres.lz
"""
import sys, os, json, base64, io
sys.path.insert(0, os.path.join(os.path.dirname(__file__), 'wii'))
import numpy as np
from PIL import Image
from lz import unlz
from brres import brres
from mdl0 import mdl0
from mesh import read_obj
from tex0 import tex0

src = sys.argv[1]
d = open(src, 'rb').read()
if d[:4] != b'bres': d = unlz(d)
r = brres(d)
M = mdl0(d, r['3DModels(NW4R)']['mr001_03'])
assert len(M['bones']) == 1 and len(M['objs']) == 1, 'expected one rigid part'
verts, tris = read_obj(d, M['objs'][0])
P, N, U = M['pos'][0][1], M['nrm'][0][1], M['uv'][0][1]
# one vertex per (position, normal, uv) combination
key = {}; pos = []; nrm = []; uv = []; idx = []
for t in tris:
    for v in (t[0], t[2], t[1]):  # the Wii's front faces wind the other way round
        k = (verts[v]['pos'], verts[v]['nrm'], verts[v]['uv0'])
        if k not in key:
            key[k] = len(pos); pos.append(P[k[0]]); n = N[k[1]]; nrm.append(n / (np.linalg.norm(n) or 1)); uv.append(U[k[2]])
        idx.append(key[k])
img, _ = tex0(d, r['Textures(NW4R)']['w_body'])
buf = io.BytesIO(); Image.fromarray(img[..., :3]).save(buf, 'PNG', optimize=True)
r4 = lambda a, n: [round(float(x), n) for x in np.asarray(a).ravel()]
out = os.path.join(os.path.dirname(__file__), '..', 'js15', 'world', 'watasyModel.js')
with open(out, 'w') as f:
    f.write('// Generated by tools/extract_watasy.py from the game file files/mr001/npc/mr001_03.brres.lz. Do not edit.\n')
    f.write('// The long-necked dinosaur in the pool by the rope bridge: map units, its own (bone) space, triangles wound for three.js.\n')
    f.write('export const WATASY = ' + json.dumps({
        'position': r4(pos, 2), 'normal': r4(nrm, 4), 'uv': r4(uv, 5), 'index': idx,
        'texture': 'data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode(),
    }, separators=(',', ':')) + ';\n')
print(f'{len(pos)} vertices, {len(idx)//3} triangles, texture {img.shape[1]}x{img.shape[0]} -> {os.path.normpath(out)} ({os.path.getsize(out)//1024} KB)')
