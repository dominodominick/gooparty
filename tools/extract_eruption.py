#!/usr/bin/env python3
"""The volcano eruption, from the game's own files: the crater on top of the volcano (map piece m001_40) and a falling
volcanic bomb, a "meteor" (m001_44), with their animations (files/mr001/map/motion/):
  m001_40_3  the crater rumbles before it blows (200 frames, loops)
  m001_40_2  the crater erupts: it squashes down and heaves back up (121 frames)
  m001_44    a meteor falls: it comes in from behind and above, spinning, and lands on its own origin (31 frames)
Each piece is rigid on one bone. For every frame this keeps the 3x4 matrix that takes the piece from where the map has
it (props baked in their bind pose in island.glb) to where the animation puts it: bone(frame) x inverse(bone(bind)).
Written to js15/world/eruptionData.js.

Usage:  python3 tools/extract_eruption.py path/to/map.brres(.lz) path/to/motion/
"""
import sys, os, json, math
sys.path.insert(0, os.path.join(os.path.dirname(__file__), 'wii'))
import numpy as np
from lz import unlz
from brres import brres, be, group
from mdl0 import mdl0
from chr0 import chr0, sample

raw = open(sys.argv[1], 'rb').read(); d = raw if raw[:4] == b'bres' else unlz(raw)
MODELS = brres(d)['3DModels(NW4R)']; MOT = sys.argv[2]

def rot(r):
    x, y, z = [math.radians(v) for v in r]
    Rx = np.array([[1, 0, 0], [0, math.cos(x), -math.sin(x)], [0, math.sin(x), math.cos(x)]])
    Ry = np.array([[math.cos(y), 0, math.sin(y)], [0, 1, 0], [-math.sin(y), 0, math.cos(y)]])
    Rz = np.array([[math.cos(z), -math.sin(z), 0], [math.sin(z), math.cos(z), 0], [0, 0, 1]])
    return Rz @ Ry @ Rx
def trs(T, R, S):
    m = np.eye(4); m[:3, :3] = rot(R) @ np.diag(S); m[:3, 3] = T; return m

def clip(model, name):
    M = mdl0(d, MODELS[model]); bones = M['bones']
    draw = M['defs']['DrawOpa'][0][3]; piece = bones[draw]['name']
    a = open(os.path.join(MOT, name + '.branm.lz'), 'rb').read(); a = unlz(a) if a[:4] != b'bres' else a
    r = brres(a); C = chr0(a, next(iter(r['AnmChr(NW4R)'].values()))); F = C['frames']
    def local(b, f):
        e = C['bones'].get(b['name']); t = e['tracks'] if e else {}; code = e['code'] if e else 0
        ident = code >> 1 & 1
        vals = {}
        for k, rest, idv, flag in (('T', b['T'], (0, 0, 0), ident or code >> 2 & 1), ('R', b['R'], (0, 0, 0), ident or code >> 2 & 1), ('S', b['S'], (1, 1, 1), ident or code >> 3 & 1)):
            if k in t: vals[k] = [sample(x, f) if not isinstance(x, float) else x for x in t[k]]
            else: vals[k] = list(idv) if (e and flag) else list(rest)
        return trs(vals['T'], vals['R'], vals['S'])
    def world(i, f, bind=False):
        m = trs(bones[i]['T'], bones[i]['R'], bones[i]['S']) if bind else local(bones[i], f)
        p = bones[i]['parent']
        return world(p, f, bind) @ m if p >= 0 else m
    inv = np.linalg.inv(world(draw, 0, True))
    skin = [[round(float(x), 4) for x in (world(draw, f) @ inv)[:3].ravel()] for f in range(F)]
    shows = None
    for v in r.get('AnmVis(NW4R)', {}).values():
        for bn, e in group(a, v + be('i', a, v + 0x10)[0]):
            if bn != piece: continue
            fl = be('I', a, e + 4)[0]
            bits = [fl & 1] * F if fl & 2 else [int(c) for c in ''.join(format(be('I', a, e + 8 + 4 * k)[0], '032b') for k in range((F + 31) // 32))[:F]]
            shows = [bits[0]] + [f for f in range(1, F) if bits[f] != bits[f - 1]]
    # where the piece's own origin (its bone) is in the model at bind: the meteor lands on its model's origin
    return {'frames': F, 'skin': skin, **({'shows': shows} if shows else {})}

data = {
    'fps': 60,
    'crater': {'rumble': clip('m001_40', 'm001_40_3'), 'erupt': clip('m001_40', 'm001_40_2')},
    'meteor': clip('m001_44', 'm001_44'),
}
dst = os.path.join(os.path.dirname(__file__), '..', 'js15', 'world', 'eruptionData.js')
with open(dst, 'w') as f:
    f.write('// Generated by tools/extract_eruption.py from the game\'s map.brres (m001_40 crater, m001_44 meteor) and their\n')
    f.write('// animations (m001_40_3 rumble, m001_40_2 erupt, m001_44 fall). Do not edit. Per frame, a 3x4 row-major matrix that moves\n')
    f.write('// the piece from where the map has it (its bind pose, map units) to where the animation puts it.\n')
    f.write('export const ERUPTION = ' + json.dumps(data, separators=(',', ':')) + ';\n')
print({k: (v['frames'] if 'frames' in v else {kk: vv['frames'] for kk, vv in v.items()}) for k, v in data.items() if k != 'fps'}, os.path.getsize(dst) // 1024, 'KB', 'meteor shows', data['meteor'].get('shows'))
